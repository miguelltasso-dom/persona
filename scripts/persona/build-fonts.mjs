#!/usr/bin/env node
/**
 * Persona fonts (Muse). Sources: persona-assets/fonts/*.woff2 — Latin subsets of
 * Fredoka[wdth,wght] and Nunito[wght] from github.com/google/fonts (SIL OFL 1.1, see OFL-*.txt), made with:
 *   pyftsubset <font>.ttf --unicodes="U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+2000-206F,U+2074,U+20AC,U+2122,U+2190-2199,U+2212,U+2215,U+2713,U+2026,U+00B7" --flavor=woff2 --layout-features='*'
 * The client asset route serves only images, so fonts ship inline as data URIs in a global stylesheet
 * (no CDN, works offline in the desktop app).
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '../..')
const SRC = join(ROOT, 'persona-assets/fonts')
const OUT = join(ROOT, 'packages/persona/client-ui-persona/src/client/theme/fonts/persona-fonts.generated.css')

const faces = [
  { family: 'Persona Fredoka', file: 'fredoka-latin.woff2', weight: '300 700', stretch: '75% 125%' },
  { family: 'Persona Nunito', file: 'nunito-latin.woff2', weight: '200 1000', stretch: 'normal' },
  { family: 'Persona Geist', file: 'geist-variable.woff2', weight: '100 900', stretch: 'normal' },
]

const css = [
  '/* Generated by scripts/persona/build-fonts.mjs — do not edit. Fredoka + Nunito, SIL OFL 1.1 (persona-assets/fonts/OFL-*.txt). */',
  ...faces.map(face => {
    const data = readFileSync(join(SRC, face.file)).toString('base64')
    return [
      '@font-face {',
      `  font-family: '${face.family}';`,
      `  src: url(data:font/woff2;base64,${data}) format('woff2');`,
      `  font-weight: ${face.weight};`,
      `  font-stretch: ${face.stretch};`,
      '  font-style: normal;',
      '  font-display: swap;',
      '}',
    ].join('\n')
  }),
].join('\n\n')
writeFileSync(OUT, `${css}\n`)
console.log(`Wrote ${OUT} (${(css.length / 1024).toFixed(0)} KiB)`)

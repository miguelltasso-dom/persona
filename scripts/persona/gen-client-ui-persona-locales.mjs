#!/usr/bin/env node
/**
 * Generate typed locale dictionaries for client-ui-persona.
 * pt and en come from locale-sources; zh, ja, es, fr, de, ru mirror en.
 */

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '../..')
const PKG = join(ROOT, 'packages/persona/client-ui-persona')
const SOURCES = join(PKG, 'locale-sources')

/** @type {ReadonlyArray<{ file: string, const: string, ns: string, keyType: string }>} */
const BUNDLES = [
  { file: 'shell', const: 'SHELL_NS', ns: 'persona.shell', keyType: 'ShellKey' },
  { file: 'onboarding', const: 'ONBOARDING_NS', ns: 'persona.onboarding', keyType: 'OnboardingKey' },
  { file: 'persona-editor', const: 'PERSONA_EDITOR_NS', ns: 'persona.personaEditor', keyType: 'PersonaEditorKey' },
  { file: 'hire', const: 'HIRE_NS', ns: 'persona.hire', keyType: 'HireKey' },
]

function readJson(name) {
  return JSON.parse(readFileSync(join(SOURCES, name), 'utf8'))
}

function tsString(value) {
  return `'${String(value).replace(/\\/gu, '\\\\').replace(/'/gu, '\\\'')}'`
}

function serializeDict(obj, indent = 2) {
  const lines = Object.entries(obj).map(([key, value]) =>
    `${' '.repeat(indent)}'${key}': ${tsString(value)},`)
  return `{\n${lines.join('\n')}\n}`
}

function writeBundle({ file, const: constName, ns, keyType }) {
  const pt = readJson(`${file}.pt.json`)
  const en = readJson(`${file}.en.json`)
  const keys = Object.keys(en)
  const ptKeys = Object.keys(pt)
  if (keys.length !== ptKeys.length || keys.some(k => pt[k] === undefined)) {
    console.error(`${file}.pt.json and ${file}.en.json key sets must match`)
    process.exit(1)
  }
  const derived = { zh: en, ja: en, es: en, fr: en, de: en, ru: en }
  const outDir = join(PKG, 'src/client/locale', file)
  const out = join(outDir, 'locales.ts')
  const body = `/** Generated by scripts/persona/gen-client-ui-persona-locales.mjs — do not edit. */

/** Locale namespace (${ns}). */
export const ${constName} = '${ns}'

/** Portuguese (Brazil) copy; keys define {@link ${keyType}}. */
export const pt = ${serializeDict(pt)} as const

/** English copy. */
export const en = ${serializeDict(en)} as const

export const zh = ${serializeDict(derived.zh)} as const
export const ja = ${serializeDict(derived.ja)} as const
export const es = ${serializeDict(derived.es)} as const
export const fr = ${serializeDict(derived.fr)} as const
export const de = ${serializeDict(derived.de)} as const
export const ru = ${serializeDict(derived.ru)} as const

export type ${keyType} = keyof typeof pt
`
  mkdirSync(outDir, { recursive: true })
  writeFileSync(out, body)
  console.log(`Wrote ${out}`)
}

for (const bundle of BUNDLES) writeBundle(bundle)

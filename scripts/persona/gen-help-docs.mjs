#!/usr/bin/env node
/**
 * Muse · Ajuda e Novidades: docs/persona/*.md → client-ui-persona/src/client/help/generated-help.ts
 * Parses markdown at BUILD time (mdast) into a tiny JSON block tree, so the client bundle ships no markdown parser
 * and never renders raw HTML. Links between guides (./x.md) become in-app navigation (`doc`).
 * Order follows docs/persona/README.md; `novidades.md` is exported separately as the release notes.
 */
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { basename, dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { fromMarkdown } from 'mdast-util-from-markdown'
import { gfmFromMarkdown } from 'mdast-util-gfm'
import { gfm } from 'micromark-extension-gfm'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '../..')
const DOCS = join(ROOT, 'docs/persona')
const OUT = join(ROOT, 'packages/persona/client-ui-persona/src/client/help/generated-help.ts')

const slug = s => s.toLowerCase().normalize('NFD').replace(/[̀-ͯ]/gu, '').replace(/[^a-z0-9]+/gu, '-').replace(/^-|-$/gu, '')
const plain = node => node.value ?? (node.children ?? []).map(plain).join('')

function inline(nodes) {
  const out = []
  for (const n of nodes ?? []) {
    if (n.type === 'text') out.push({ t: 'text', v: n.value })
    else if (n.type === 'strong') out.push({ t: 'strong', c: inline(n.children) })
    else if (n.type === 'emphasis') out.push({ t: 'em', c: inline(n.children) })
    else if (n.type === 'inlineCode') out.push({ t: 'code', v: n.value })
    else if (n.type === 'break') out.push({ t: 'text', v: ' ' })
    else if (n.type === 'link') {
      const m = /^\.\/([a-z0-9-]+)\.md(?:#([a-z0-9-]+))?$/u.exec(n.url)
      out.push(m ? { t: 'link', doc: m[1], ...(m[2] ? { anchor: m[2] } : {}), c: inline(n.children) } : { t: 'link', href: n.url, c: inline(n.children) })
    } else if (n.children) out.push(...inline(n.children))
    else if (n.value) out.push({ t: 'text', v: n.value })
  }
  return out
}

function blocks(nodes, headings) {
  const out = []
  for (const n of nodes ?? []) {
    if (n.type === 'heading') {
      const text = plain(n)
      const id = slug(text)
      if (n.depth > 1) headings.push({ id, text, level: n.depth })
      out.push({ t: 'h', level: n.depth, id, c: inline(n.children) })
    } else if (n.type === 'paragraph') out.push({ t: 'p', c: inline(n.children) })
    else if (n.type === 'list') out.push({ t: n.ordered ? 'ol' : 'ul', items: n.children.map(li => blocks(li.children, headings)) })
    else if (n.type === 'code') out.push({ t: 'code', v: n.value })
    else if (n.type === 'blockquote') out.push({ t: 'quote', c: blocks(n.children, headings) })
    else if (n.type === 'table') out.push({ t: 'table', rows: n.children.map(r => r.children.map(cell => inline(cell.children))) })
    else if (n.type === 'thematicBreak') out.push({ t: 'hr' })
  }
  return out
}

function parse(file) {
  const md = readFileSync(join(DOCS, file), 'utf8')
  const tree = fromMarkdown(md, { extensions: [gfm()], mdastExtensions: [gfmFromMarkdown()] })
  const headings = []
  const body = blocks(tree.children, headings)
  const h1 = tree.children.find(n => n.type === 'heading' && n.depth === 1)
  const firstP = tree.children.find(n => n.type === 'paragraph')
  return {
    id: basename(file, '.md'),
    title: h1 ? plain(h1) : basename(file, '.md'),
    summary: firstP ? plain(firstP).slice(0, 180) : '',
    headings,
    // lowercase, accent-free text for client search
    text: slug(plain(tree)).replace(/-/gu, ' '),
    blocks: body.filter(b => !(b.t === 'h' && b.level === 1)),
  }
}

const readme = readFileSync(join(DOCS, 'README.md'), 'utf8')
const order = [...readme.matchAll(/\]\(\.\/([a-z0-9-]+)\.md\)/gu)].map(m => m[1])
// Guides for the people who BUILD the app (packaging, checks) live in docs/persona too, but they never go into the Help of the person who uses it.
const BUILDER_GUIDES = new Set(['empacotar.md'])
const files = readdirSync(DOCS).filter(f => f.endsWith('.md') && f !== 'README.md' && f !== 'novidades.md' && !BUILDER_GUIDES.has(f))
const docs = files.map(parse).sort((a, b) => {
  const ia = order.indexOf(a.id); const ib = order.indexOf(b.id)
  return (ia < 0 ? 999 : ia) - (ib < 0 ? 999 : ib)
})
let notes = null
try { notes = parse('novidades.md') } catch { /* optional */ }

mkdirSync(dirname(OUT), { recursive: true })
writeFileSync(OUT, `/* Generated by scripts/persona/gen-help-docs.mjs from docs/persona — do not edit. */
/* eslint-disable */
import type { HelpDoc } from './help-types.ts'

export const HELP_DOCS: readonly HelpDoc[] = ${JSON.stringify(docs)}

export const RELEASE_NOTES: HelpDoc | null = ${JSON.stringify(notes)}
`)
console.log(`help: ${docs.length} guides${notes ? ' + novidades' : ''} → ${OUT.slice(ROOT.length + 1)}`)
